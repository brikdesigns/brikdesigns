#!/usr/bin/env node
// Hardcoded-literal gate for brikdesigns.com CSS.
//
// Closes the blind spot in lint-tokens.mjs: that gate only validates `var(--…)`
// *references*, so a raw literal (`gap: 2px`, `border-radius: 8px`, `color:
// #fff`) with no token to inspect sails through. This one flags raw spatial,
// radius, border-width, typographic, and colour literals in token-governed CSS
// properties — and for the length families reports whether an exact token
// exists (fix it) or none does (a candidate design-system gap to raise).
//
// See scripts/lib/hardcoded-values.mjs for the category/property map and the
// deliberate exclusions (layout dimensions, font-weight, var/calc/clamp, zero).
//
// Allowlist: scripts/hardcoded-allowlist.txt — whole-file grandfathering for
// files not yet migrated (transitional burn-down) or intentionally literal
// (the /value Paper port, kept literal per sign-off). Per-line escape hatch:
// `/* bds-lint-ignore hardcoded — <reason> */`.
//
// Usage:
//   npm run lint:hardcoded
//   npm run lint:hardcoded -- --write-allowlist   # snapshot current offending
//                                                 # files into the allowlist
//
// Why: brikdesigns customer-stories `.story-meta__item { gap: 2px }` shipped
// unflagged. Ships the gate in the same change as the fix (CLAUDE.md).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { glob } from 'glob';
import { loadTokenIndex, findHardcodedViolations } from './lib/hardcoded-values.mjs';

const ROOT = process.cwd();
const HERE = path.dirname(fileURLToPath(import.meta.url));
const ALLOWLIST_PATH = path.join(HERE, 'hardcoded-allowlist.txt');
const args = new Set(process.argv.slice(2));
const WRITE_ALLOWLIST = args.has('--write-allowlist');

function readAllowlist() {
  if (!fs.existsSync(ALLOWLIST_PATH)) return new Set();
  return new Set(
    fs
      .readFileSync(ALLOWLIST_PATH, 'utf8')
      .split('\n')
      .map((l) => l.replace(/#.*$/, '').trim())
      .filter(Boolean)
  );
}

const index = loadTokenIndex([
  path.join(ROOT, 'node_modules/@brikdesigns/bds/dist/tokens.css'),
  path.join(ROOT, 'src/app/globals.css'),
]);

const allowlist = WRITE_ALLOWLIST ? new Set() : readAllowlist();
const files = (await glob('src/**/*.css', { ignore: ['**/node_modules/**'] })).sort();

const all = [];
for (const file of files) {
  const rel = file.replace(/\\/g, '/');
  if (allowlist.has(rel)) continue;
  all.push(...findHardcodedViolations(rel, fs.readFileSync(file, 'utf8'), index));
}

if (WRITE_ALLOWLIST) {
  const offending = [...new Set(all.map((v) => v.file))].sort();
  const body = [
    '# scripts/hardcoded-allowlist.txt',
    '# Whole-file grandfathering for the hardcoded-literal gate (lint-hardcoded.mjs).',
    '# One repo-relative path per line; `#` starts a comment.',
    '#',
    '# Two kinds of entry:',
    '#   • Permanent — intentionally literal, signed off (e.g. the /value Paper port).',
    '#   • Transitional — not yet migrated; drive this list to zero. Remove a file',
    '#     once its literals are tokenized and it passes the gate clean.',
    '#',
    '# Generated by `npm run lint:hardcoded -- --write-allowlist`.',
    '',
    ...offending,
    '',
  ].join('\n');
  fs.writeFileSync(ALLOWLIST_PATH, body);
  console.log(`Wrote ${offending.length} file(s) to ${path.relative(ROOT, ALLOWLIST_PATH)}`);
  process.exit(0);
}

if (all.length === 0) {
  console.log(`OK — ${files.length} CSS file(s) scanned, no hardcoded literals in token-governed properties.`);
  process.exit(0);
}

console.error(`FAIL — ${all.length} hardcoded literal(s) in token-governed properties:\n`);
const byFile = {};
for (const v of all) (byFile[v.file] ??= []).push(v);
for (const file of Object.keys(byFile).sort()) {
  console.error(`  ${file}`);
  for (const v of byFile[file]) {
    const fix = v.dsGap
      ? '→ NO matching token (candidate design-system gap)'
      : v.suggestion
        ? `→ use ${v.suggestion}`
        : `→ use a ${v.category} token`;
    console.error(`    :${v.line}  [${v.category}] ${v.prop}: ${v.literal}   ${fix}`);
  }
  console.error('');
}
console.error('Fix options:');
console.error('  1. Replace the literal with the suggested token.');
console.error('  2. NO-matching-token = raise it: the value is a real design decision');
console.error('     with no home in the system — add a token in brik-bds, don\'t hardcode.');
console.error('  3. Genuine primitive (fluid clamp, one-off signed-off port): wrap the value');
console.error('     in var()/calc()/clamp(), or add `/* bds-lint-ignore hardcoded — <reason> */`,');
console.error('     or whole-file grandfather in scripts/hardcoded-allowlist.txt.');
process.exit(1);
